    /**
     * Compute the new step size from the error residual and the current step
     * size assuming that the stepping algorithm is first-order accurate. The
     * new step size is determined from the prescribed error tolerance value
     * recovered from <code>#getErrorTolerance()</code> and the norm of the
     * residual (note that the type of norm used is determined by
     * <code>getLebesgueNorm()</code>).
     *
     * @param h current step size
     * @param matRes residual error matrix from the stepping
     *
     * @return new step size
     *
     * @see #getErrorTolerance
     * @see #getLebesgueNorm
     * @see #compMatrixNorm
     */
    private double compNewStepSize(double h, PhaseMatrix matRes) {

        double toler = this.getErrorTolerance();
        double hmax = this.getMaxStepSize();
        double slack = this.getSlackTolerance();
        double error = compMatrixNorm(matRes);

        if (getDebugMode()) {
            if (Math.abs(h) < 1e-5) {
                LOGGER.log(Level.INFO, "compNewStepSize, h = 0");
            }

            LOGGER.log(Level.INFO, "error = {0}", error);
            if (Math.abs(error) < 1e-5) {
                LOGGER.log(Level.INFO, "compNewStepSize, error = 0");
            }
        }

        // Compute the new step size
        // new step size
        double hnew;

        if (this.getAccuracyOrder() == ACCUR_ORDER1) {
            hnew = h * Math.sqrt(toler / error);
        } else {
            hnew = h * Math.pow(toler / error, 1.0 / 3.0);
        }

        if (hmax != 0.0 && hnew > hmax) {
            hnew = hmax;
        } else if (Math.abs((hnew - h) / h) < slack) {
            hnew = h;
        }

        if (this.getDebugMode() == true) {
            LOGGER.log(Level.INFO, "residual error={0}", error);
            LOGGER.log(Level.INFO, "hnew = {0}", hnew);
        }
        return hnew;
    }

