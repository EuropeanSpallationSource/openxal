    /**
     * Perform an internal extrapolation to generate an estimate of the probe
     * state (correlation matrix) that is one order higher in accuracy than the
     * algorithm provides. Although the estimate might be higher-order accurate
     * this does not guarantee that it is any closer to the real answer. And we
     * have no way of enforcing any error tolerance.
     *
     * @param matRes the residual error matrix from the two half-step/one whole
     * step process
     * @param matState the new probe state generated by stepping
     *
     * @return an extrapolated value of the probe state
     */
    private CovarianceMatrix compInternExtrap(PhaseMatrix matRes, PhaseMatrix matState) {
        // the extrapolated matrix
        PhaseMatrix matChi;

        if (this.getAccuracyOrder() == ACCUR_ORDER1) {
            matChi = matState.plus(matRes);
        } else {
            matChi = matRes.times(1. / 3.).plus(matState);
        }

        return new CovarianceMatrix(matChi);
    }

    /**
     * Computes the full transfer matrix for a section of length <code>s</code>.
     * The returned transfer matrix is first-order accurate and includes both
     * the effects of the <code>IElement</code> and the effects of space charge.
     *
     * @param h distance for which transfer matrix will propagate probe
     * @param probe the <code>IProbe</code> object for which the transfer matrix
     * is valid
     * @param elem the <code>IElement</code> object
     *
     * @return 7x7 2nd-order accurate transfer matrix in homogeneous phase space
     * coordinates
     *
     * @throws ModelException unable to compute the transfer matrix for the
     * element
     *
     * @see #compElemTransMatrix
     * @see #compScheffTransMatrix
     */
    private PhaseMatrix compTransferMatrix(double h, EnvelopeProbe probe, IElement elem)
            throws ModelException {

        // jdg - bail if no space charge is needed:
        if (probe.bunchCharge() == 0.) {
            return this.compElemTransMatrix(h, probe, elem);
        }

        if (this.getAccuracyOrder() == ACCUR_ORDER1) {
            PhaseMatrix matPhiSc = super.compScheffMatrix(h, probe, elem);

            // We're going to try something different and ensure symplecticity
            // If we are only first-order accurate get the full transfer matrices for the two effects,
            //  multiply them, and return the combined matrix
            PhaseMatrix matPhiE = this.compElemTransMatrix(h, probe, elem);
            PhaseMatrix matPhi = matPhiE.times(matPhiSc);

            return matPhi;
        }

        // Get the transfer matrices for the two individual effects and 
        //  combine them to second-order accuracy (via Campbell-Baker-Hausdorff)        
        // Store the current probe state (for rollback)
        EnvelopeProbeState state0 = probe.cloneCurrentProbeState();

        // Get half-step transfer matrix at current probe location
        PhaseMatrix matPhi0 = this.compElemTransMatrix(h / 2.0, probe, elem);

        // Get the RMS envelopes at probe location
        // covariance matrix at entrance
        CovarianceMatrix covTau0 = probe.getCovariance();

        // Advance probe a half step for position depend transfer maps
        double pos = probe.getPosition() + h / 2.0;
        PhaseMatrix matTau1 = covTau0.conjugateTrans(matPhi0);
        CovarianceMatrix covTau1 = new CovarianceMatrix(matTau1);

        probe.setPosition(pos);
        probe.setCovariance(covTau1);

        // space charge transfer matrix
        PhaseMatrix matPhiSc = this.compScheffMatrix(h, probe, elem);

        // Compute half-step transfer matrix at new probe location        
        PhaseMatrix matPhi1 = this.compElemTransMatrix(h / 2.0, probe, elem);

        // Restore original probe state
        probe.applyState(state0);

        // Compute the full transfer matrix for the distance dblLen
        return matPhi1.times(matPhiSc.times(matPhi0));
    }
