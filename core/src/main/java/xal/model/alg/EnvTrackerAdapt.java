    /*
     *  Tracker Abstract Protocol
     */
    /**
     * Propagates the probe through the element using a second-order accurate
     * adaptive step size algorithm for space charge calculations.
     *
     * The new probe state is first computed by taken a full step with the
     * second- order accurate transfer matrix with includes space charge effect.
     * The algorithm then computes the new probe state by taking two half-steps.
     * The residual error (correlation matrix) between the two states is
     * computed. If the norm of the matrix is below the error tolerance (@see
     * #getErrorTolerance) the step may be lengthened. If the residual error is
     * greater than tolerance the step size must be shortened and the new probe
     * state recomputed.
     *
     * @param ifcProbe probe to propagate
     * @param elem element acting on probe
     *
     * @exception ModelException invalid probe type or error in advancing probe
     */
    @Override
    public void doPropagation(IProbe ifcProbe, IElement elem) throws ModelException {
        // Identify probe
        if (!(ifcProbe instanceof EnvelopeProbe)) {
            throw new IllegalArgumentException("Must be of type " + EnvelopeProbe.class.getName());
        }

        EnvelopeProbe probe = (EnvelopeProbe) ifcProbe;

        // If this is a thin element, no space charge calculations are necessary
        if (elem instanceof ThinElement) {
            this.stepThinElement(probe, elem);
            return;
        }

        // Initialize the 2nd order accurate, adaptive step size algorithm
        // current iteration counter
        int iCurCnt = 0;
        // maximum no of iterations
        int iMaxCnt = this.getMaxIterations();

        // location of probe within element
        double s = 0.0;
        // the current step size
        double h = this.getStepSize();
        // length of the element
        double L = elem.getLength();
        EnvelopeProbeState stateRef
                = // initial state of the probe 
                probe.createProbeState();

        //default temporary commented out 
        // this doesnt work for PMQ space-charge=0.. why?
        double charge = probe.bunchCharge();
        // new step size
        double hp;
        // the residual error matrix
        PhaseMatrix matRes;

        do {
            // jdg - if no charge take giant step
            if (charge == 0.) {
                // no space charge - take giant steps
                h = L - s;
            }
            // check if we would step outside the element - if so shorten step 
            if (h + s > L) {
                h = L - s;
            }

            if (getDebugMode()) {
                LOGGER.log(Level.INFO, "charge = {0}", charge);
                LOGGER.log(Level.INFO, "EnvTrackerAdapt, elem, probe.getBeamCharge() = {0} {1}", new Object[]{elem.getId(), probe.bunchCharge()});
                LOGGER.log(Level.INFO, "going to stepProbeState, h, s, L = {0} {1} {2}", new Object[]{h, s, L});
            }

            // Step the probe according to the algorithm, then compute new step size
            matRes = this.stepProbeState(h, probe, elem);
            // I am actuall not sure with space charge=0, effect of fringe field calc step size can be igonored?
            if (charge == 0.) {
                hp = h;
            } else {
                hp = this.compNewStepSize(h, matRes);
            }

            // we stepped too far - roll back and try again
            if (hp < h) {
                this.rollbackProbe(probe, stateRef);

                // our step size meets accuracy criterion - advance probe
            } else {
                stateRef = probe.createProbeState();
                s += h;
            }
            // use the new step size
            h = hp;

            if (this.getDebugMode() == true) {
                if (elem instanceof IdealDrift) {
                    LOGGER.log(Level.INFO, "IdealDrift, hp = " + hp);
                }
                LOGGER.log(Level.INFO, "propagate s=" + probe.getPosition() + " h=" + h + " hp=" + hp + " N=" + nDbgSteps++);
            }

            if (iMaxCnt != 0 && ++iCurCnt >= iMaxCnt) {
                throw new ModelException("EnvTrackerAdapt#doPropagation() - maximum iteration count exceeded.");
            }

            // do while we are still in the element
        } while (s < L);

        // save the last step size as an initial guess for the next time
        this.setStepSize(h);
    }


